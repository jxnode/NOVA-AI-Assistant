
import os
import logging

import psycopg
from psycopg.rows import dict_row

logger = logging.getLogger("nova.memory")

DATABASE_URL = os.getenv("DATABASE_URL")


def get_connection():
    database_url = os.getenv("DATABASE_URL") or DATABASE_URL

    if not database_url:
        raise RuntimeError("DATABASE_URL is not configured.")

    if database_url.startswith("postgres://"):
        database_url = database_url.replace(
            "postgres://", "postgresql://", 1
        )

    return psycopg.connect(
        database_url,
        row_factory=dict_row,
        connect_timeout=10,
    )


def initialize_database():
    with get_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS public.memories (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    content TEXT NOT NULL UNIQUE,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
            """)


def save_memory(content: str) -> dict:
    content = content.strip()

    if not content or len(content) > 500:
        raise ValueError("Memory must contain 1–500 characters.")

    with get_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute("""
                INSERT INTO public.memories (content)
                VALUES (%s)
                ON CONFLICT (content) DO NOTHING
                RETURNING id, content, created_at
            """, (content,))

            row = cursor.fetchone()

            if row is None:
                cursor.execute("""
                    SELECT id, content, created_at
                    FROM public.memories
                    WHERE content = %s
                """, (content,))
                row = cursor.fetchone()

    return dict(row)


def list_memories(limit: int = 100) -> list[dict]:
    limit = max(1, min(limit, 1000))

    with get_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute("""
                SELECT id, content, created_at
                FROM public.memories
                ORDER BY id DESC
                LIMIT %s
            """, (limit,))
            rows = cursor.fetchall()

    return [dict(row) for row in rows]


def delete_memory(memory_id: int) -> bool:
    with get_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute("""
                DELETE FROM public.memories
                WHERE id = %s
            """, (memory_id,))
            return cursor.rowcount > 0


def search_memories(
    query: str = "",
    limit: int = 20,
) -> list[dict]:
    limit = max(1, min(limit, 100))
    memories = list_memories(limit=100)

    if not query.strip():
        return memories[:limit]

    terms = set(query.lower().split())
    ranked = []

    for memory in memories:
        content = memory["content"].lower()
        score = sum(1 for term in terms if term in content)

        if score:
            ranked.append((score, memory))

    ranked.sort(key=lambda item: item[0], reverse=True)
    return [memory for _, memory in ranked[:limit]]
